#!/usr/bin/env python3
"""Writes the package-manager files for a release, from dist/checksums.txt:

  dist/dad.rb                         the Homebrew formula (for the tap mtwalli/homebrew-dad)
  dist/winget/mtwalli.dad*.yaml       the winget manifests (for microsoft/winget-pkgs)

  python3 tools/release/manifests.py 0.2.0
"""
import os
import sys

REPO = "mtwalli/dad-lang"
HOMEPAGE = f"https://github.com/{REPO}"
SUMMARY = "Arabic programming language for web apps"


def checksums(path):
    out = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            parts = line.split()
            if len(parts) == 2:
                out[parts[1].lstrip("*")] = parts[0]
    return out


def homebrew(version, sums):
    base = f"{HOMEPAGE}/releases/download/v{version}"

    def target(os_, arch):
        name = f"dad_{os_}_{arch}.tar.gz"
        return f'      url "{base}/{name}"\n      sha256 "{sums[name]}"\n'

    return f'''# Generated by tools/release/manifests.py for Ḍād {version}.
class Dad < Formula
  desc "{SUMMARY}"
  homepage "{HOMEPAGE}"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
{target("darwin", "arm64")}    end
    on_intel do
{target("darwin", "amd64")}    end
  end

  on_linux do
    on_arm do
{target("linux", "arm64")}    end
    on_intel do
{target("linux", "amd64")}    end
  end

  def install
    bin.install "dad"
    bin.install_symlink "dad" => "ضاد"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/dad version")
    (testpath/"hello.dad").write("اطبع(1 + 2)\\n")
    assert_equal "3\\n", shell_output("#{{bin}}/dad run #{{testpath}}/hello.dad")
  end
end
'''


def winget(version, sums):
    ident = "mtwalli.dad"
    base = f"{HOMEPAGE}/releases/download/v{version}"
    head = f"# Generated by tools/release/manifests.py for Ḍād {version}.\nPackageIdentifier: {ident}\nPackageVersion: {version}\n"
    files = {}
    files[f"{ident}.yaml"] = head + "DefaultLocale: en-US\nManifestType: version\nManifestVersion: 1.6.0\n"
    installers = ""
    for arch, wa in (("amd64", "x64"), ("arm64", "arm64")):
        name = f"dad_windows_{arch}.zip"
        installers += (
            f"  - Architecture: {wa}\n"
            f"    InstallerUrl: {base}/{name}\n"
            f"    InstallerSha256: {sums[name].upper()}\n"
            f"    NestedInstallerFiles:\n"
            f"      - RelativeFilePath: dad_windows_{arch}\\dad.exe\n"
            f"        PortableCommandAlias: dad\n"
        )
    files[f"{ident}.installer.yaml"] = (
        head + "InstallerType: zip\nNestedInstallerType: portable\nInstallers:\n" + installers
        + "ManifestType: installer\nManifestVersion: 1.6.0\n"
    )
    files[f"{ident}.locale.en-US.yaml"] = head + f"""PackageLocale: en-US
Publisher: mtwalli
PublisherUrl: https://github.com/mtwalli
PackageName: Ḍād
PackageUrl: {HOMEPAGE}
License: MIT
LicenseUrl: {HOMEPAGE}/blob/main/LICENSE
ShortDescription: {SUMMARY}
Description: Ḍād (ضاد) is a programming language with Arabic keywords for building whole web apps - interface, server and data in one language. The dad command runs, checks, formats, serves and builds programs.
Moniker: dad
Tags:
  - arabic
  - programming-language
  - compiler
  - web
ReleaseNotesUrl: {HOMEPAGE}/releases/tag/v{version}
ManifestType: defaultLocale
ManifestVersion: 1.6.0
"""
    return files


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: manifests.py <version>")
    version = sys.argv[1].lstrip("v")
    sums = checksums("dist/checksums.txt")
    with open("dist/dad.rb", "w", encoding="utf-8") as f:
        f.write(homebrew(version, sums))
    os.makedirs("dist/winget", exist_ok=True)
    for name, text in winget(version, sums).items():
        with open(os.path.join("dist/winget", name), "w", encoding="utf-8") as f:
            f.write(text)
    print("dist/dad.rb")
    print("dist/winget/")


if __name__ == "__main__":
    main()
