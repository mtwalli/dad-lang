"""Generates the icons of the «أيقونة» element from Lucide (ISC licence).

Writes internal/interp/icons.go and the «icons» block of
internal/codegen/js/runtime.js, so the interpreter and the compiled code draw
the same icons, and tools/icons/gallery.html for the docs. Run from the repository root with the lucide-static package:

    npm install lucide-static && python3 tools/icons/gen.py node_modules/lucide-static/icons
"""

import json
import re
import subprocess
import sys

# Arabic name → Lucide icon. The page is right to left, so «التالي» (next) points left.
ICONS = {
    "بحث": "search", "أضف": "plus", "ناقص": "minus", "حذف": "trash-2", "تعديل": "pencil",
    "حفظ": "save", "إغلاق": "x", "تم": "check", "رئيسية": "house", "إعدادات": "settings",
    "مستخدم": "user", "مستخدمون": "users", "بريد": "mail", "هاتف": "phone", "تقويم": "calendar",
    "ساعة": "clock", "نجمة": "star", "قلب": "heart", "سلة": "shopping-cart", "تنزيل": "download",
    "رفع": "upload", "رابط": "link", "قفل": "lock", "خروج": "log-out", "دخول": "log-in",
    "معلومة": "info", "تحذير": "triangle-alert", "نجاح": "circle-check", "خطر": "octagon-alert",
    "التالي": "chevron-left", "السابق": "chevron-right", "أعلى": "chevron-up", "أسفل": "chevron-down",
    "قائمة": "menu", "ملف": "file-text", "مجلد": "folder", "صورة": "image", "موقع": "map-pin",
    "تحديث": "refresh-cw", "مشاركة": "share-2", "طباعة": "printer", "نسخ": "copy", "عين": "eye",
    "جرس": "bell", "شمس": "sun", "قمر": "moon", "كتاب": "book-open", "رسم_بياني": "chart-column",
    "إرسال": "send", "عالم": "globe",
}


def inner(path):
    s = open(path, encoding="utf-8").read()
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    body = re.search(r"<svg[^>]*>(.*)</svg>", s, flags=re.S).group(1)
    body = re.sub(r"\s*\n\s*", "", body)
    return re.sub(r"\s*/>", "/>", body).strip()


def main(folder):
    icons = {name: inner(f"{folder}/{file}.svg") for name, file in ICONS.items()}
    names = sorted(icons)
    go = ["// Code generated by tools/icons/gen.py from Lucide (ISC licence); DO NOT EDIT.", "",
          "package interp", "", "// Icons are the drawings of «أيقونة», by Arabic name: the inside of a 24×24 SVG.",
          "var Icons = map[string]string{"]
    for n in names:
        go.append(f"\t{json.dumps(n, ensure_ascii=False)}: {json.dumps(icons[n], ensure_ascii=False)},")
    go.append("}")
    open("internal/interp/icons.go", "w", encoding="utf-8").write("\n".join(go) + "\n")
    subprocess.run(["gofmt", "-w", "internal/interp/icons.go"], check=True)

    # the gallery in the interface guide (docs/ui.md, docs/ui.en.md)
    cells = "".join(
        f'<figure><svg viewBox="0 0 24 24" aria-hidden="true">{icons[n]}</svg><figcaption>{n}</figcaption></figure>'
        for n in sorted(icons, key=lambda n: list(ICONS).index(n)))
    open("tools/icons/gallery.html", "w", encoding="utf-8").write(
        '<div class="dad-icon-grid" dir="rtl" lang="ar">' + cells + "</div>\n")

    path = "internal/codegen/js/runtime.js"
    js = open(path, encoding="utf-8").read()
    block = ("  // icons:begin — generated by tools/icons/gen.py from Lucide (ISC licence)\n  const icons = {\n" +
             "".join(f"    {json.dumps(n, ensure_ascii=False)}: {json.dumps(icons[n], ensure_ascii=False)},\n" for n in names) +
             "  };\n  // icons:end\n")
    if "// icons:begin" in js:
        js = re.sub(r"  // icons:begin.*?// icons:end\n", lambda m: block, js, flags=re.S)
    else:
        js = js.replace("  let ui = null; // the render in progress\n", block + "  let ui = null; // the render in progress\n", 1)
    open(path, "w", encoding="utf-8").write(js)


if __name__ == "__main__":
    main(sys.argv[1])
